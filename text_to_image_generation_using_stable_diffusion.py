print("✓ Stable Diffusion pipeline deployed")
print("✓ Natural language → High-quality images")
print(f"✓ GPU acceleration: {device.upper()}")
print("✓ Optimized via prompt batching")
print(f"✓ Average inference time: {total_time/len(all_images):.2f}s/image")
print("="*70)