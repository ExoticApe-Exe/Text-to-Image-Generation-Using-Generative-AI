# STEP 7: SAVE A SAMPLE IMAGE
# =============================================================================

if len(all_images) > 0:
    all_images[0].save('/content/sample_generated_image.png')
    print("\n✓ Sample image saved to /content/sample_generated_image.png")

print("\n" + "="*70)
print("PROJECT 3 COMPLETE!")
