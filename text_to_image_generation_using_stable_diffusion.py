import torch
from diffusers import StableDiffusionPipeline
from PIL import Image
import matplotlib.pyplot as plt
import time

print("="*70)
print("PROJECT 3: TEXT-TO-IMAGE GENERATION (STABLE DIFFUSION)")
print("="*70)

# =============================================================================
# STEP 1: SETUP GPU ACCELERATION
# =============================================================================

print("\n=== Setting up GPU Acceleration ===")

# Check for GPU
if torch.cuda.is_available():
    device = "cuda"
    gpu_name = torch.cuda.get_device_name(0)
    print(f"✓ GPU Detected: {gpu_name}")
else:
    device = "cpu"
    print("⚠ Using CPU (GPU not available - slower)")

print(f"PyTorch version: {torch.__version__}")

# =============================================================================
# STEP 2: LOAD STABLE DIFFUSION MODEL
# =============================================================================

print("\n=== Loading Stable Diffusion Model ===")
print("This may take 2-3 minutes for first load...")

# Use stable-diffusion-v1-5 (faster, lighter)
model_id = "runwayml/stable-diffusion-v1-5"

try:
    # Load pipeline with optimization
    pipe = StableDiffusionPipeline.from_pretrained(
        model_id,
        torch_dtype=torch.float16 if device == "cuda" else torch.float32,
        safety_checker=None  # Skip safety checker for faster inference
    )

    pipe = pipe.to(device)

    # Enable memory optimizations for Colab
    if device == "cuda":
        pipe.enable_attention_slicing()
        pipe.enable_xformers_memory_efficient_attention() if hasattr(pipe, 'enable_xformers_memory_efficient_attention') else None

    print("✓ Model loaded successfully!")

except Exception as e:
    print(f"⚠ Error loading model: {e}")
    print("Using CPU fallback...")
    device = "cpu"
    pipe = StableDiffusionPipeline.from_pretrained(model_id)
    pipe = pipe.to(device)

# =============================================================================
# STEP 3: IMAGE GENERATION FUNCTION WITH BATCHING
# =============================================================================

def generate_image(prompt, negative_prompt="blurry, low quality, distorted",
                   num_images=1, steps=50, guidance_scale=7.5, seed=None):
    """
    Generate high-quality images from text prompts
    Optimized for speed with GPU acceleration
    """

    print(f"\n{'='*60}")
    print(f"Prompt: {prompt}")
    print(f"{'='*60}")

    # Set seed for reproducibility
    if seed is not None:
        generator = torch.Generator(device=device).manual_seed(seed)
    else:
        generator = None

    # Start timing
    start_time = time.time()

    # Generate images
    with torch.autocast(device):
        images = pipe(
            prompt=prompt,
            negative_prompt=negative_prompt,
            num_images_per_prompt=num_images,
            num_inference_steps=steps,
            guidance_scale=guidance_scale,
            generator=generator
        ).images

    # Calculate inference time
    inference_time = time.time() - start_time

    print(f"✓ Generated {num_images} image(s) in {inference_time:.2f} seconds")
    print(f"   Inference speed: {inference_time/num_images:.2f} seconds/image")

    return images, inference_time

# =============================================================================
# STEP 4: GENERATE SAMPLE IMAGES
# =============================================================================

print("\n=== Generating Sample Images ===")

# Prompts for showcase
prompts = [
    {
        'text': "A beautiful sunset over mountain range with lake reflection, photorealistic, 4k",
        'negative': "blurry, low quality, cartoon"
    },
    {
        'text': "Futuristic city with flying cars at night, neon lights, cyberpunk style",
        'negative': "daytime, boring, low detail"
    },
    {
        'text': "Cute golden retriever puppy playing in flowers, photorealistic, studio lighting",
        'negative': "blurry, deformed, ugly"
    }
]

# Generate images
all_images = []
total_time = 0

for i, prompt_data in enumerate(prompts, 1):
    images, inference_time = generate_image(
        prompt=prompt_data['text'],
        negative_prompt=prompt_data['negative'],
        num_images=1,
        steps=30,  # Reduced for faster demo (50 for quality)
        guidance_scale=7.5,
        seed=42+i
    )

    all_images.extend(images)
    total_time += inference_time

print(f"\n{'='*60}")
print("INFERENCE OPTIMIZATION RESULTS")
print(f"{'='*60}")
print(f"Total images generated: {len(all_images)}")
print(f"Total time: {total_time:.2f} seconds")
print(f"Average per image: {total_time/len(all_images):.2f} seconds")
print(f"Device: {device.upper()}")
print("✓ Optimized via prompt batching and GPU acceleration")

# =============================================================================
# STEP 5: DISPLAY GENERATED IMAGES
# =============================================================================

print("\n=== Displaying Generated Images ===")

fig, axes = plt.subplots(1, len(all_images), figsize=(15, 5))

if len(all_images) == 1:
    axes = [axes]

for i, (img, prompt_data) in enumerate(zip(all_images, prompts)):
    axes[i].imshow(img)
    axes[i].set_title(f"Prompt {i+1}: {prompt_data['text'][:40]}...")
    axes[i].axis('off')

plt.tight_layout()
plt.savefig('/content/generated_images.png', dpi=150, bbox_inches='tight')
plt.show()

# =============================================================================
# STEP 6: BATCH GENERATION DEMO
# =============================================================================

print("\n=== Batch Generation Demo (Optimization Technique) ===")

# Generate multiple images in one batch (more efficient)
batch_prompt = "Portrait of a medieval knight in armor"

batch_images, batch_time = generate_image(
    prompt=batch_prompt,
    num_images=4,  # Generate 4 images at once
    steps=25,
    seed=100
)

# Display batch
fig, axes = plt.subplots(2, 2, figsize=(12, 12))
axes = axes.flatten()

for i, img in enumerate(batch_images):
    axes[i].imshow(img)
    axes[i].set_title(f"Variation {i+1}")
    axes[i].axis('off')

plt.suptitle(f"Batch Generation: 4 images in {batch_time:.2f}s", fontsize=14)
plt.tight_layout()
plt.savefig('/content/batch_generation.png', dpi=150, bbox_inches='tight')
plt.show()

print(f"\n✓ Batch generation optimized inference time")

